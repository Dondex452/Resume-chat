/**
 * M10 — give every design the two country-only blocks (PRD §8, §5.4).
 *
 * Both are **disabled**, so the ten designs render exactly as they did before
 * M10; a country preset turns them on, and the renderer emits nothing for them
 * while no personal data is present. They sit at the end of the main column of
 * every design — a sensible shared default, since a preset can reorder them.
 */
export function withCountrySections(schema: TemplateSchema): TemplateSchema {
  const hasPersonal = schema.sections.some((section) => section.key === 'personal');
  const hasSignature = schema.sections.some((section) => section.key === 'signature');
  if (hasPersonal && hasSignature) return schema;

  const additions = [
    ...(hasPersonal ? [] : [createPersonalSection(PERSONAL_SECTION_ORDER)]),
    ...(hasSignature ? [] : [createSignatureSection(SIGNATURE_SECTION_ORDER)]),
  ];
  return { ...schema, sections: [...schema.sections, ...additions] };
}

