/**
 * Resolver used by the app: returns the schema for a built-in template id.
 * Unknown ids fall back to `minimal`, so a stale stored `template_id` can never
 * render an empty sheet.
 */
export function getBuiltinTemplateSchema(templateId: string): TemplateSchema {
  return BUILTIN_TEMPLATE_SCHEMAS[templateId] ?? BUILTIN_TEMPLATE_SCHEMAS.minimal;
}
